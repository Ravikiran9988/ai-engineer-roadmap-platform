/**
 * Helper: get all videos for a specific topic, optionally filtered by path/type/difficulty.
 */
export function getVideosForTopic(topicId, { path, type, difficulty } = {}) {
  return VIDEOS
    .filter(v => v.topicId === topicId)
    .filter(v => !path || v.learningPaths.includes(path))
    .filter(v => !type || v.type === type)
    .filter(v => !difficulty || v.difficulty === difficulty)
    .sort((a, b) => a.order - b.order);
}

/**
 * Helper: get all videos for a specific subtopic.
 */
export function getVideosForSubtopic(subtopicId) {
  return VIDEOS
    .filter(v => v.subtopicId === subtopicId)
    .sort((a, b) => a.order - b.order);
}
