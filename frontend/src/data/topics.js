/**
 * Get all topics for a given path.
 * Works without importing learningPaths to avoid circular deps.
 */
export function getTopicsForPath(pathId) {
  if (pathId === 'advanced') return TOPICS;
  return TOPICS.filter(t => t.paths.includes(pathId));
}
